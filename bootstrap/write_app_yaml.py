#!/usr/bin/env python3
"""Generates `app/app.yaml` from the bundle's variables, in the PREDEPLOY hook so it is synced with the app.

WHY IT IS GENERATED RATHER THAN HAND-EDITED PER TARGET: `resources.apps.<key>.config` (with `command` and
`env`) survives `bundle validate`, resolves every variable in `-o json`, and then GOES NOWHERE — the
terraform provider's `databricks_app` schema has no such attribute and `apps get` returns no such field.
That looked like it worked for a while on another app in this workspace and then produced a container with
no environment at all, while the deploy's exit code, `bundle validate` and `apps get` RUNNING were all
green. So the runtime config lives in a real `app.yaml`, written here.

⚠️ A committed `app/app.yaml` is deliberate too: the manual install route is "download the repo, upload the
   folder, create the app in the UI", and a folder with no app.yaml produces an app that starts with no
   command — which reads as broken code rather than as a missing file. After a bundle deploy your working
   tree will show app/app.yaml as modified; that is this script, not you.

⛔ AN EMPTY VALUE FAILS THE DEPLOY *AFTER* THE APP HAS STARTED. The Apps API answers "Must specify
   environment variable source using either `value` or `valueFrom`", and because the hook that starts the
   app runs earlier the app is left ACTIVE with no deployment — running and serving nothing. So this refuses
   an empty value here, loudly, rather than passing it on.
"""
import sys

USAGE = "usage: write_app_yaml.py <path> KEY=VALUE [KEY=VALUE ...]"

HEADER = """# ── THE APP'S RUNTIME CONFIG ────────────────────────────────────────────────────────────────────────
# GENERATED by bootstrap/write_app_yaml.py from the bundle's variables (predeploy hook). It is committed so
# the manual install works unedited: upload this folder, point an app at it, and the wheel runs.
#
# There is no password and no secret in here by design — the owner removed the settings gate on 2026-09-23
# (the app runs on the hosts' own laptops), so nothing in this file is sensitive.
"""


def main(argv):
    if len(argv) < 3:
        print(USAGE, file=sys.stderr)
        return 2
    path, pairs = argv[1], argv[2:]
    lines = [HEADER, 'command: ["python", "app.py"]', "env:"]
    for pair in pairs:
        if "=" not in pair:
            print(f"[write_app_yaml] not a KEY=VALUE: {pair!r}", file=sys.stderr)
            return 2
        key, _, value = pair.partition("=")
        key, value = key.strip(), value.strip()
        if not value:
            print(f"[write_app_yaml] ⛔ {key} has an EMPTY value. The Apps API refuses that and the deploy "
                  f"would fail AFTER the app started, leaving it running with no deployment. Use an "
                  f"explicit sentinel such as 'none' instead.", file=sys.stderr)
            return 1
        # Quote every value: an unquoted `660` is fine but an unquoted `on`/`no`/`1.15` is a YAML type
        # surprise waiting to happen, and the app parses its own environment as strings anyway.
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'  - name: {key}')
        lines.append(f'    value: "{escaped}"')
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[write_app_yaml] wrote {path} with {len(pairs)} environment entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
